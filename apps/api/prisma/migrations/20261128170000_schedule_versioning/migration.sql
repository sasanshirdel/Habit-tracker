-- Hand-written: what Prisma cannot express.
-- A change's dates are in the habit window; a correction is exactly a non-create change that
-- starts before the user's today, and it always carries a reason; create rows have no "before".
ALTER TABLE "habit_schedule_changes"
  ADD CONSTRAINT "habit_schedule_changes_dates_check" CHECK (
    "effective_from" BETWEEN DATE '2000-01-01' AND DATE '2099-12-31'
    AND "local_today" BETWEEN DATE '2000-01-01' AND DATE '2099-12-31'
  ),
  ADD CONSTRAINT "habit_schedule_changes_correction_check" CHECK (
    "is_correction" = ("operation" <> 'create' AND "effective_from" < "local_today")
    AND (NOT "is_correction" OR "reason" IS NOT NULL)
  ),
  ADD CONSTRAINT "habit_schedule_changes_reason_check" CHECK (
    "reason" IS NULL OR char_length("reason") BETWEEN 1 AND 500
  ),
  ADD CONSTRAINT "habit_schedule_changes_affected_check" CHECK (
    "affected_recorded_days" >= 0 AND ("is_correction" OR "affected_recorded_days" = 0)
  ),
  ADD CONSTRAINT "habit_schedule_changes_snapshot_check" CHECK (
    ("operation" = 'create') = ("before" IS NULL)
    AND jsonb_typeof("after") = 'array'
    AND ("before" IS NULL OR jsonb_typeof("before") = 'array')
  );

-- Append-only: an audit row is never edited (rows still disappear with their habit or account
-- through ON DELETE CASCADE, which is a DELETE, not an UPDATE).
CREATE FUNCTION "habit_schedule_changes_append_only"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'habit_schedule_changes rows are append-only' USING ERRCODE = 'check_violation';
END;
$$;

CREATE TRIGGER "habit_schedule_changes_no_update"
  BEFORE UPDATE ON "habit_schedule_changes"
  FOR EACH ROW EXECUTE FUNCTION "habit_schedule_changes_append_only"();
