import { z } from 'zod';
import { HABIT_CHECK_IN_ACTIONS } from '@habit/shared-types';
import {
  HABIT_LIMITS,
  HABIT_SCHEDULE_PERIODS,
  HABIT_TARGET_COMPARISONS,
  habitCheckInSchema,
  habitStatusRangeSchema,
} from '@habit/shared-validation';
import { component, errorEnvelopeWith } from '../../openapi/index.js';

/**
 * Schemas of the check-in and status routes (backlog P3-04, ADR-0031). Request rules come from
 * `@habit/shared-validation`; response schemas mirror `@habit/shared-types` (asserted in
 * `habit-check-in.test.ts`).
 */

export const habitIdParamSchema = z.uuid().meta({ description: 'Id of one of your habits.' });

export const checkInBodySchema = habitCheckInSchema.meta({
  description:
    'One check-in operation. `operationId` is generated by the client once per user action ' +
    '(a UUID) and sent again with every retry of it. `value` is required for `set` and ' +
    'forbidden otherwise: 1 (done) or 0 for binary and frequency habits, whole seconds up to ' +
    '86400 for duration, whole lapses for negative, 0..1000000 with up to 3 decimals for numeric ' +
    'and custom. `expectedVersion` (optional) is the record `version` you last saw, or `null` ' +
    'for "no record": the write is then refused with 409 `VERSION_CONFLICT` if the day changed ' +
    'meanwhile (offline clients must send it). Without it the last write wins.',
});

export const statusRangeQuerySchema = habitStatusRangeSchema.meta({
  description: `Inclusive local dates (YYYY-MM-DD), at most ${HABIT_LIMITS.statusRangeMaxDays} days.`,
});

const localDate = (description: string) => z.iso.date().meta({ description });
const targetSchema = z.strictObject({
  comparison: z.enum(HABIT_TARGET_COMPARISONS),
  value: z.number(),
});

export const habitDayProgressSchema = component(
  z.strictObject({
    value: z.number(),
    target: targetSchema.nullable().meta({
      description: 'Target of the version in effect; `null` for binary/frequency (done = 1).',
    }),
    met: z.boolean(),
    partial: z.boolean().meta({ description: 'Some progress, not yet an "at least" target.' }),
    percent: z.int().min(0).max(100),
  }),
  { id: 'HabitDayProgress', description: 'How a recorded value compares with the day’s target.' },
);

export const habitDayStatusSchema = component(
  z.strictObject({
    date: localDate('The local date.'),
    status: z.enum(['completed', 'missed', 'due', 'skipped', 'paused', 'not_scheduled']),
    timing: z.enum(['past', 'today', 'future']).meta({
      description: 'Relative to your today in your profile time zone.',
    }),
    scheduleState: z.enum(['due', 'flexible', 'off', 'paused', 'inactive']),
    inactiveReason: z.enum(['before_start', 'after_end', 'archived', 'no_version']).nullable(),
    pausedState: z.enum(['due', 'flexible', 'off']).nullable(),
    versionId: z.uuid().nullable().meta({ description: 'Schedule version in effect that day.' }),
    graceDays: z.int().nullable(),
    record: z.strictObject({ value: z.number().nullable(), skipped: z.boolean() }).nullable(),
    progress: habitDayProgressSchema.nullable(),
    openUntil: localDate(
      'Last day a Due day can still be completed before it counts as Missed.',
    ).nullable(),
    period: z.int().min(0).nullable().meta({ description: 'Index into `periods`.' }),
  }),
  {
    id: 'HabitDayStatus',
    description:
      'The computed status of a habit on one day (never stored): Completed, Missed, Due, Skipped, Paused or Not scheduled, with progress against the target (ADR-0031).',
  },
);

export const habitPeriodStatusSchema = component(
  z.strictObject({
    versionId: z.uuid(),
    kind: z.enum(HABIT_SCHEDULE_PERIODS),
    start: localDate('First day of the week or month.'),
    end: localDate('Last day of the week or month.'),
    totalDays: z.int(),
    coveredDays: z.int(),
    pausedDays: z.int(),
    activeDays: z.int(),
    timesPerPeriod: z.int(),
    required: z.int().meta({ description: 'Prorated by the schedule (ADR-0029).' }),
    partial: z.boolean(),
    skippedDays: z.int(),
    target: z.int().meta({ description: 'Completions needed after skips.' }),
    completed: z.int(),
    remaining: z.int(),
    graceDays: z.int(),
    openUntil: localDate('After this day an unmet period is Missed.'),
    status: z.enum(['met', 'in_progress', 'missed', 'not_required']),
  }),
  {
    id: 'HabitPeriodStatus',
    description: 'A week or month of a "N times per period" habit, judged as a whole.',
  },
);

export const habitStatusRangeResponseSchema = component(
  z.strictObject({
    habitId: z.uuid(),
    today: localDate('Your local date the statuses were computed for.'),
    from: localDate('First day.'),
    to: localDate('Last day.'),
    days: z.array(habitDayStatusSchema),
    periods: z.array(habitPeriodStatusSchema),
  }),
  { id: 'HabitStatusRange', description: 'Statuses of one habit over a date range.' },
);

export const habitOccurrenceRecordSchema = component(
  z.strictObject({
    habitId: z.uuid(),
    localDate: localDate('The local date.'),
    value: z.number().nullable().meta({ description: '`null` exactly when skipped.' }),
    skipped: z.boolean(),
    version: z
      .int()
      .min(1)
      .meta({ description: 'Send as `expectedVersion` to write conditionally.' }),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
  }),
  { id: 'HabitOccurrenceRecord', description: 'What is recorded for one habit on one day.' },
);

export const habitCheckInRecordSchema = component(
  z.strictObject({
    id: z.uuid(),
    habitId: z.uuid(),
    operationId: z.uuid(),
    localDate: localDate('The day the operation is about.'),
    action: z.enum(HABIT_CHECK_IN_ACTIONS),
    value: z.number().nullable(),
    changed: z.boolean().meta({ description: 'Whether the stored record changed.' }),
    occurrenceVersion: z.int().min(1).nullable(),
    localToday: localDate('Your local date when the operation was accepted.'),
    createdAt: z.iso.datetime(),
  }),
  { id: 'HabitCheckIn', description: 'One accepted check-in operation (append-only log).' },
);

export const habitCheckInResultSchema = component(
  z.strictObject({
    replayed: z.boolean().meta({
      description:
        '`true` when this `operationId` had already been accepted: nothing was written again and the current state is returned.',
    }),
    checkIn: habitCheckInRecordSchema,
    occurrence: habitOccurrenceRecordSchema.nullable(),
    day: habitDayStatusSchema,
    period: habitPeriodStatusSchema.nullable(),
  }),
  { id: 'HabitCheckInResult', description: 'The accepted check-in and the day’s status now.' },
);

export const habitNotFoundErrorSchema = component(
  errorEnvelopeWith(z.literal('NOT_FOUND'), z.unknown().optional()),
  {
    id: 'HabitNotFoundError',
    description:
      '404 `NOT_FOUND`: no such habit of yours — identical for one that does not exist, was deleted or belongs to someone else.',
  },
);

export const checkInConflictErrorSchema = component(
  errorEnvelopeWith(
    z.enum(['VERSION_CONFLICT', 'IDEMPOTENCY_KEY_REUSED', 'HABIT_ARCHIVED']),
    z.strictObject({ currentVersion: z.int().min(1).nullable() }).optional(),
  ),
  {
    id: 'CheckInConflictError',
    description:
      '409: `VERSION_CONFLICT` (the record is not the `expectedVersion`; `details.currentVersion` is the stored one, `null` = no record), `IDEMPOTENCY_KEY_REUSED` (this `operationId` was used for a different request) or `HABIT_ARCHIVED` (restore the habit first).',
  },
);

export const checkInRefusedErrorSchema = component(
  errorEnvelopeWith(
    z.enum(['DATE_IN_FUTURE', 'DATE_NOT_TRACKED', 'SKIP_NOT_ALLOWED']),
    z.unknown().optional(),
  ),
  {
    id: 'CheckInRefusedError',
    description:
      '422: `DATE_IN_FUTURE` (after your today in your profile time zone), `DATE_NOT_TRACKED` (before the habit’s start, after its end, archived, or no schedule that day) or `SKIP_NOT_ALLOWED` (only scheduled, not paused days can be skipped).',
  },
);
