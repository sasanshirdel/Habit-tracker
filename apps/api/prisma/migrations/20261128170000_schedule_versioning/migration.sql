-- P3-03 (ADR-0030): schedule versioning — each schedule version snapshots the calendar settings
-- its periods are counted in, and every schedule change is recorded in an append-only audit table.
-- Additive only: one enum type, two columns on habit_schedule_versions (backfilled from the
-- owner's preferences, then NOT NULL), one unique index on habit_schedule_versions(id, habit_id),
-- one new table with its indexes, keys, CHECKs and an append-only trigger. The table is new in
-- P3-01 and has no production rows yet, so the backfill and SET NOT NULL are cheap.
-- Rollback before real data exists: drop habit_schedule_changes, its trigger function, the enum,
-- the unique index and the two columns.
--
-- Generated by `prisma migrate diff`, then the backfill and the constraints Prisma cannot express
-- were added by hand (kept in step with the service by src/modules/habits/habits.schema.test.ts).
-- CreateEnum
CREATE TYPE "habit_schedule_operation" AS ENUM ('create', 'split', 'replace');

-- AlterTable: added NULL-able, backfilled, then made NOT NULL (no default on purpose — every
-- writer must snapshot the user's preferences explicitly).
ALTER TABLE "habit_schedule_versions" ADD COLUMN     "calendar" "calendar_system",
ADD COLUMN     "week_start" "week_start";

-- Backfill: existing versions get their owner's current preferences — what P3-02 callers were told
-- to pass until this snapshot existed — or the user_preferences column defaults (gregorian /
-- monday) for an account without a preferences row.
UPDATE "habit_schedule_versions" AS v
SET "calendar" = p."calendar", "week_start" = p."week_start"
FROM "user_preferences" AS p
WHERE p."user_id" = v."user_id";
UPDATE "habit_schedule_versions" SET "calendar" = 'gregorian' WHERE "calendar" IS NULL;
UPDATE "habit_schedule_versions" SET "week_start" = 'monday' WHERE "week_start" IS NULL;

ALTER TABLE "habit_schedule_versions" ALTER COLUMN "calendar" SET NOT NULL,
ALTER COLUMN "week_start" SET NOT NULL;

